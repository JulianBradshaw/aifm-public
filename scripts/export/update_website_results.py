def extract_date_from_results_dir(results_dir: Path) -> str:
    """Extract date from results directory name.

    Expected format: results_20251216_024237 -> 20251216
    Falls back to current date if parsing fails.
    """
    import re
    name = results_dir.name
    # Try to match results_YYYYMMDD_HHMMSS pattern
    match = re.search(r'results_(\d{8})_\d{6}', name)
    if match:
        return match.group(1)
    # Try to match just YYYYMMDD
    match = re.search(r'(\d{8})', name)
    if match:
        return match.group(1)
    # Fall back to current date
    return datetime.now().strftime("%Y%m%d")


def generate_run_id(forecaster: str, date_str: str) -> str:
    """Generate a run ID from forecaster name and date."""
    return f"{forecaster}-{date_str}"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Copy results from outputs/ to website directories",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__
    )
    parser.add_argument(
        "--results-dir", type=str, required=True,
        help="Path to results directory (e.g., outputs/results_20251216_024237)"
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Preview changes without copying files"
    )
    parser.add_argument(
        "--clean", action="store_true",
        help="Remove existing files in destination directories before copying"
    )
    parser.add_argument(
        "--default-run", type=str, default="eli",
        choices=["eli", "daniel"],
        help="Which run to set as default (default: eli)"
    )
    return parser.parse_args()


def find_run_directory(base_dir: Path, run_name: str) -> Optional[Path]:
    """Find the actual run directory within a results subdirectory.

    The structure is: results_dir/eli/20251216_024237/
    We need to find the timestamped subdirectory.
    """
    run_base = base_dir / run_name
    if not run_base.exists():
        return None

    # Find the timestamped subdirectory
    subdirs = [d for d in run_base.iterdir() if d.is_dir()]
    if not subdirs:
        return None

    # Return the most recent one
    return max(subdirs, key=lambda p: p.stat().st_mtime)


def get_num_samples(run_dir: Path) -> int:
    """Try to read num_samples from the run's metadata."""
    # Try rollouts.cache.json first (faster)
    cache_file = run_dir / "rollouts.cache.json"
    if cache_file.exists():
        try:
            with open(cache_file) as f:
                data = json.load(f)
                if "num_samples" in data:
                    return data["num_samples"]
                if "milestones" in data:
                    # Count samples from first milestone
                    for milestone_data in data["milestones"].values():
                        if isinstance(milestone_data, list):
                            return len(milestone_data)
        except (json.JSONDecodeError, KeyError):
            pass

    # Try counting lines in rollouts.jsonl
    rollouts_file = run_dir / "rollouts.jsonl"
    if rollouts_file.exists():
        try:
            with open(rollouts_file) as f:
                return sum(1 for _ in f)
        except Exception:
            pass

    # Default
    return 1000


def copy_file(src: Path, dst: Path, dry_run: bool) -> bool:
    """Copy a file, creating parent directories as needed."""
    if not src.exists():
        return False

    if dry_run:
        print(f"  Would copy: {src.name}")
        return True

    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    return True


def clean_directory(dir_path: Path, dry_run: bool) -> None:
    """Remove all contents from a directory."""
    if not dir_path.exists():
        return

    if dry_run:
        print(f"  Would clean: {dir_path}")
        return

    for item in dir_path.iterdir():
        if item.is_dir():
            shutil.rmtree(item)
        else:
            item.unlink()


def update_runs_json(
    runs_data: dict,
    dry_run: bool
) -> None:
    """Update the runs.json file."""
    runs_json_path = REPO_ROOT / "app" / "results" / "data" / "runs" / "runs.json"

    if dry_run:
        print(f"\nWould update {runs_json_path}:")
        print(json.dumps(runs_data, indent=2))
        return

    runs_json_path.parent.mkdir(parents=True, exist_ok=True)
    with open(runs_json_path, "w") as f:
        json.dump(runs_data, f, indent=2)
        f.write("\n")


def read_sc_horizon_manifest(run_dir: Path) -> Optional[Dict[str, Any]]:
    """Read SC horizon manifest from run directory.

    Args:
        run_dir: Path to run directory

    Returns:
        Manifest dict with median_sc_date, median_sc_decimal_year, generated_csvs
        or None if manifest doesn't exist
    """
    manifest_path = run_dir / "horizon_trajectories" / "sc_horizon_manifest.json"
    if not manifest_path.exists():
        return None

    try:
        with open(manifest_path) as f:
            return json.load(f)
    except (json.JSONDecodeError, IOError) as e:
        print(f"    WARNING: Could not read SC horizon manifest: {e}")
        return None


def copy_sc_horizon_csvs(
    run_dir: Path,
    public_dst: Path,
    dry_run: bool,
    copy_to_public_root: bool = False,
) -> tuple[int, int, Optional[Dict[str, Any]]]:
    """Copy SC horizon trajectory CSVs from run to public directory.

    Args:
        run_dir: Source run directory
        public_dst: Destination public directory for this run
        dry_run: If True, don't actually copy files
        copy_to_public_root: If True, also copy CSVs to public/ root

    Returns:
        Tuple of (copied_count, missing_count, manifest_data)
    """
    manifest = read_sc_horizon_manifest(run_dir)
    if manifest is None:
        print("    No SC horizon manifest found, skipping SC CSVs")
        return 0, 0, None

    copied = 0
    missing = 0
    horizon_src_dir = run_dir / "horizon_trajectories"
    horizon_dst_dir = public_dst / "horizon_trajectories"

    for csv_filename in manifest.get("generated_csvs", []):
        src = horizon_src_dir / csv_filename
        dst = horizon_dst_dir / csv_filename
        if copy_file(src, dst, dry_run):
            copied += 1

            # Also copy to public root if requested (for backward compatibility)
            if copy_to_public_root:
                public_root_dst = REPO_ROOT / "public" / csv_filename
                copy_file(src, public_root_dst, dry_run)
        else:
            missing += 1
            print(f"    WARNING: Missing SC CSV {csv_filename}")

    return copied, missing, manifest


def main():
    args = parse_args()

    results_dir = Path(args.results_dir)
    if not results_dir.exists():
        print(f"ERROR: Results directory not found: {results_dir}")
        return 1

    # Extract date from results directory name for generating run IDs
    date_str = extract_date_from_results_dir(results_dir)

    print(f"Results directory: {results_dir}")
    print(f"Date extracted: {date_str}")
    print(f"Dry run: {args.dry_run}")
    print(f"Clean: {args.clean}")
    print()

    # Track statistics
    total_copied = 0
    total_missing = 0
    runs_processed = []

    # Process each run
    for run_name, config in RUN_CONFIGS.items():
        run_dir = find_run_directory(results_dir, run_name)
        if run_dir is None:
            print(f"Skipping {run_name}: not found in {results_dir}")
            continue

        print(f"Processing {run_name} from {run_dir}")

        # Generate run ID dynamically
        run_id = generate_run_id(config["forecaster"], date_str)
        public_dst = REPO_ROOT / "public" / "results" / run_id
        data_dst = REPO_ROOT / "app" / "results" / "data" / "runs" / run_id

        # Clean directories if requested
        if args.clean:
            print(f"  Cleaning {public_dst}")
            clean_directory(public_dst, args.dry_run)
            print(f"  Cleaning {data_dst}")
            clean_directory(data_dst, args.dry_run)

        # Copy images to public/results/<run-id>/
        print(f"  Copying images to {public_dst}")
        copied = 0
        missing = 0
        for rel_path in REQUIRED_IMAGES:
            src = run_dir / rel_path
            dst = public_dst / rel_path
            if copy_file(src, dst, args.dry_run):
                copied += 1
            else:
                missing += 1
                print(f"    WARNING: Missing {rel_path}")

        print(f"    Copied: {copied}, Missing: {missing}")
        total_copied += copied
        total_missing += missing

        # Copy CSVs to app/results/data/runs/<run-id>/
        print(f"  Copying CSVs to {data_dst}")
        copied = 0
        missing = 0
        for rel_path in REQUIRED_CSVS:
            src = run_dir / rel_path
            dst = data_dst / rel_path
            if copy_file(src, dst, args.dry_run):
                copied += 1
            else:
                missing += 1
                print(f"    WARNING: Missing {rel_path}")

        print(f"    Copied: {copied}, Missing: {missing}")
        total_copied += copied
        total_missing += missing

        # Copy JSON files to app/results/data/runs/<run-id>/
        print(f"  Copying JSON files to {data_dst}")
        copied = 0
        missing = 0
        for rel_path in REQUIRED_JSONS:
            src = run_dir / rel_path
            dst = data_dst / rel_path
            if copy_file(src, dst, args.dry_run):
                copied += 1
            else:
                missing += 1
                # JSON files are optional (e.g., correlation_matrix may not exist for no-corr runs)
                print(f"    Note: {rel_path} not found (optional)")

        print(f"    Copied: {copied}, Missing: {missing}")
        total_copied += copied
        # Don't count optional JSON files as missing in total
        # total_missing += missing

        # Copy SC horizon CSVs (with manifest)
        # Copy to public root for default run (for backward compatibility with component)
        is_default_run = (config["forecaster"] == RUN_CONFIGS[args.default_run]["forecaster"])
        print(f"  Copying SC horizon CSVs to {public_dst / 'horizon_trajectories'}")
        sc_copied, sc_missing, sc_manifest = copy_sc_horizon_csvs(
            run_dir, public_dst, args.dry_run,
            copy_to_public_root=is_default_run
        )
        if sc_copied > 0 or sc_missing > 0:
            print(f"    SC CSVs - Copied: {sc_copied}, Missing: {sc_missing}")
        total_copied += sc_copied
        total_missing += sc_missing

        # Get num_samples for this run
        num_samples = get_num_samples(run_dir)

        # Build run entry with optional median SC data
        run_entry = {
            "id": run_id,
            "label": config["label"],
            "forecaster": config["forecaster"],
            "date": datetime.now().strftime("%Y-%m-%d"),
            "numSamples": num_samples,
            "dataPath": f"runs/{run_id}",
        }

        # Add median SC data if available from manifest
        if sc_manifest:
            if sc_manifest.get("median_sc_date"):
                run_entry["medianScDate"] = sc_manifest["median_sc_date"]
            if sc_manifest.get("median_sc_decimal_year"):
                run_entry["medianScDecimalYear"] = sc_manifest["median_sc_decimal_year"]

        runs_processed.append(run_entry)

        print()

    if not runs_processed:
        print("ERROR: No runs processed")
        return 1

    # Copy no-correlation comparison images for each forecaster (if available)
    no_corr_configs = [
        ("eli_no_corr", "eli_no_correlation"),
        ("daniel_no_corr", "daniel_no_correlation"),
    ]
    for src_dir_name, dst_dir_name in no_corr_configs:
        no_corr_dir = find_run_directory(results_dir, src_dir_name)
        if no_corr_dir:
            print(f"Processing {src_dir_name} comparison figures from {no_corr_dir}")
            no_corr_dst = REPO_ROOT / "public" / "results" / dst_dir_name

            if args.clean:
                print(f"  Cleaning {no_corr_dst}")
                clean_directory(no_corr_dst, args.dry_run)

            print(f"  Copying no-correlation comparison images to {no_corr_dst}")
            copied = 0
            missing = 0
            for rel_path in NO_CORRELATION_IMAGES:
                src = no_corr_dir / rel_path
                dst = no_corr_dst / rel_path
                if copy_file(src, dst, args.dry_run):
                    copied += 1
                else:
                    missing += 1
                    print(f"    WARNING: Missing {rel_path}")

            print(f"    Copied: {copied}, Missing: {missing}")
            total_copied += copied
            total_missing += missing
            print()
        else:
            print(f"No {src_dir_name} directory found, skipping its comparison figures")
            print()

    # Update runs.json
    default_forecaster = RUN_CONFIGS[args.default_run]["forecaster"]
    default_run_id = generate_run_id(default_forecaster, date_str)
    runs_data = {
        "version": 1,
        "defaultRun": default_run_id,
        "runs": runs_processed,
    }

    print("Updating runs.json")
    update_runs_json(runs_data, args.dry_run)

    # Print summary
    print("\n" + "=" * 60)
    print("SUMMARY")
    print("=" * 60)
    print(f"Total files copied: {total_copied}")
    print(f"Total files missing: {total_missing}")
    print(f"Runs processed: {len(runs_processed)}")

    if args.dry_run:
        print("\nThis was a dry run. No files were actually copied.")
        print("Run without --dry-run to apply changes.")

    return 0


if __name__ == "__main__":
    exit(main())
