#!/usr/bin/env python3
"""Generate a self-contained HTML browser for Monte Carlo batch-rollout runs.

Scans an outputs root (default: mc_outputs/ at the repo root) for <run_name>/<stamp>/summary.json
and writes <root>/viewer.html — a two-pane viewer (run list + per-run stats, metadata, and
figure gallery), at feature parity with plan_a_covert_proj/pipeline/make_viewer.py.

Everything is referenced by RELATIVE path (<run_name>/<stamp>/...), so the viewer works both
as a file:// page and under `python -m http.server` started from the outputs root.

SIZE DISCIPLINE: rollouts.jsonl is ~100MB+ per run and is NEVER read here. The only per-run
payload embedded in the HTML is the compact summary.json produced by summarize_rollouts.py
(a few KB) plus relative links to figures/CSVs already on disk. A run directory that has
rollouts.jsonl but no summary.json is summarized automatically (streamed, never slurped).

CONCURRENCY: a background watcher may be rsyncing a run into the root and regenerating the
viewer at the same time. collect() tolerates half-populated run dirs (rsync temp files,
missing/partial summary.json, files vanishing mid-walk) and marks such runs "incomplete"
rather than failing; viewer.html is written atomically so a torn file is never observed.

    python scripts/pipelines/make_mc_viewer.py                    # rebuild mc_outputs/viewer.html
    python scripts/pipelines/make_mc_viewer.py --root some/dir    # different outputs root
    python scripts/pipelines/make_mc_viewer.py --resummarize      # force summary.json rebuild
"""
