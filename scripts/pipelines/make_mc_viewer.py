# Small text artefacts rendered inline in the detail pane (rather than just linked).
INLINE_CSV = ("milestone_summary.csv", "median_trajectory_milestones.csv")
INLINE_TXT = ("rollout_summary.txt",)
MAX_INLINE_BYTES = 20_000

# A run is flagged "incomplete" when it is missing any of these.
CORE_ARTIFACTS = ("metadata.json", "milestone_summary.csv")


def _parse_stamp(name):
    try:
        return datetime.strptime(name, "%Y%m%d_%H%M%S")
    except ValueError:
        return None


def _read_text(path, limit=MAX_INLINE_BYTES):
    try:
        if path.stat().st_size > limit:
            return None
        return path.read_text(errors="replace")
    except OSError:
        return None


def _parse_csv(text):
    """Tiny CSV reader (no quoted-comma support needed for these files)."""
    rows = [ln.split(",") for ln in text.strip().splitlines() if ln.strip()]
    return rows or None


_TOTAL_RE = re.compile(r"^Total Rollouts:\s*([0-9]+)\s*$", re.M)


def _stale_warning(fname, txt, summary):
    """Flag an inline text artefact whose own totals contradict summary.json.

    rollout_summary.txt used to be generated by a RolloutsReader that parsed
    rollouts.cache.json as JSONL and reported "Total Rollouts: 1" for every run (fixed in
    scripts/plotting_utils/rollouts_reader.py). Rather than hardcoding a caveat for that one
    signature, cross-check the number the file states against the number the summarizer
    counted — this also catches a .txt left over from a different or older run.
    """
    if fname != "rollout_summary.txt":
        return None
    n_total = summary.get("n_total")
    if not isinstance(n_total, int) or n_total <= 1:
        return None
    m = _TOTAL_RE.search(txt)
    if not m:
        return None
    stated = int(m.group(1))
    if stated == n_total:
        return None
    return (f"⚠ this file reports {stated} rollout(s) but the run contains {n_total} — it is "
            f"stale or was produced by the pre-fix rollout_summary.py. Regenerate with "
            f"`python scripts/analysis/rollout_summary.py <run_dir>` where rollouts.jsonl lives; "
            f"until then trust the ANCHOR MODES table above.")


FORECAST_DIR = "forecast_data"
FORECAST_DIST = "milestone_pdfs_overlay_distributions.csv"
FORECAST_STATS = "milestone_pdfs_overlay_statistics.csv"
FORECAST_CDF = "milestone_pdfs_overlay_cdf.csv"


def _read_forecast(run_dir, prefix, summary):
    """Load the production forecast CSVs this run exported, if they were pulled.

    These are written by scripts/export/generate_overlay_distributions.py — the same
    generator scripts/pipelines/forecast_export.py drives to build app/forecast/data/, so
    the viewer's topline shows exactly what the /forecast page shows, with no math of its
    own. Only the two overlay files are embedded (~15 KB of numbers per run); the
    conditional-timing CSVs stay on disk as links.
    """
    fdir = run_dir / FORECAST_DIR
    dist_fp, stats_fp = fdir / FORECAST_DIST, fdir / FORECAST_STATS
    if not (dist_fp.exists() and stats_fp.exists()):
        return None

    dist_rows = _parse_csv(dist_fp.read_text(errors="replace")) or []
    if len(dist_rows) < 2:
        return None
    header = [h.strip() for h in dist_rows[0]]
    names = header[1:]
    xs, series = [], [[] for _ in names]
    for row in dist_rows[1:]:
        if len(row) != len(header):
            continue
        try:
            xs.append(round(float(row[0]), 4))
            for i in range(len(names)):
                series[i].append(round(float(row[i + 1]), 4))
        except ValueError:
            continue
    if not xs:
        return None

    stats_rows = _parse_csv(stats_fp.read_text(errors="replace")) or []
    stats = []
    if len(stats_rows) >= 2:
        skeys = [h.strip() for h in stats_rows[0]]
        for row in stats_rows[1:]:
            if len(row) != len(skeys):
                continue
            rec = {}
            for k, v in zip(skeys, row):
                try:
                    rec[k] = float(v) if k != "milestone_name" else v
                except ValueError:
                    rec[k] = v
            stats.append(rec)

    # Empirical CDF, on the same time grid (verified identical) so the x array is shared.
    # Values are used raw, exactly as app/forecast/.../page.tsx does: each curve plateaus at
    # that milestone's achievement rate rather than saturating at 1.0.
    cdf = None
    cdf_fp = fdir / FORECAST_CDF
    if cdf_fp.exists():
        crows = _parse_csv(cdf_fp.read_text(errors="replace")) or []
        if len(crows) == len(dist_rows) and [c.strip() for c in crows[0]] == header:
            cser = [[] for _ in names]
            aligned = True
            for row in crows[1:]:
                if len(row) != len(header):
                    aligned = False
                    break
                try:
                    for i in range(len(names)):
                        cser[i].append(round(float(row[i + 1]), 5))
                except ValueError:
                    aligned = False
                    break
            if aligned and all(len(c) == len(xs) for c in cser):
                cdf = cser

    # The overlay's denominator excludes failed rollouts entirely (they are not counted as
    # "not achieved"), so surface how many of the sampled rollouts it never saw.
    counted = int(stats[0]["total_rollouts"]) if stats and "total_rollouts" in stats[0] else None
    sampled = summary.get("n_total")
    dropped = (sampled - counted) if isinstance(sampled, int) and isinstance(counted, int) else None

    return {
        "x": xs,
        "names": names,
        "series": series,
        "stats": stats,
        "cdf": cdf,
        # achievement_rate_pct/100 per milestone — page.tsx renormalizes the PDF to integrate
        # to exactly this, so the viewer needs it to reproduce production's curve.
        "rates": {s0["milestone_name"]: s0.get("achievement_rate_pct", 0) / 100.0
                  for s0 in stats if "milestone_name" in s0},
        "cdf_href": (f"{prefix}/{FORECAST_DIR}/{FORECAST_CDF}") if cdf else None,
        "counted": counted,
        "sampled": sampled,
        "dropped_failed": dropped,
        "dist_href": f"{prefix}/{FORECAST_DIR}/{FORECAST_DIST}",
        "stats_href": f"{prefix}/{FORECAST_DIR}/{FORECAST_STATS}",
    }


def _walk_files(run_dir):
    """Every regular file under run_dir, as posix relpaths, skipping dotfiles.

    rsync stages incoming files as `.<name>.<random>` in the destination directory, so
    dotfiles are both noise and a reliable mid-pull signal. Races (a file vanishing between
    listing and stat) are swallowed — a concurrent pull must never break the generator.
    """
    files, temps = [], []
    for dirpath, dirnames, filenames in os.walk(run_dir, onerror=lambda e: None):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        rel_dir = os.path.relpath(dirpath, run_dir)
        rel_dir = "" if rel_dir == "." else rel_dir.replace(os.sep, "/")
        for fn in sorted(filenames):
            rel = f"{rel_dir}/{fn}" if rel_dir else fn
            if fn.startswith("."):
                temps.append(rel)
                continue
            files.append(rel)
    return files, temps


def _ensure_summary(run_dir, resummarize=False, allow_summarize=True):
    """Return the run's summary dict, generating summary.json on the fly when possible.

    Returns None when there is nothing to summarize (no summary.json and no local
    rollouts.jsonl) or when the on-disk summary.json is unreadable/partial — the caller
    then renders the run as "incomplete" instead of dropping it.
    """
    sfile = run_dir / "summary.json"
    if sfile.exists() and not resummarize:
        try:
            data = json.loads(sfile.read_text())
            if isinstance(data, dict):
                return data
        except Exception:
            return None   # partial/torn file mid-pull
    if not allow_summarize or not (run_dir / "rollouts.jsonl").exists():
        return None
    print(f"  summarizing {run_dir} (streaming rollouts.jsonl)…")
    try:
        summary = summarize_run(str(run_dir))
    except Exception as e:
        print(f"  ! could not summarize {run_dir}: {e}", file=sys.stderr)
        return None
    tmp = sfile.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(summary, indent=1))
    os.replace(tmp, sfile)
    return summary


def _group_figures(rel_paths):
    """{subdir_label: [relpath, ...]} preserving on-disk order, root files first."""
    groups = {}
    for rel in rel_paths:
        parts = rel.split("/")
        label = "/".join(parts[:-1]) if len(parts) > 1 else "(run root)"
        groups.setdefault(label, []).append(rel)
    ordered = {}
    if "(run root)" in groups:
        ordered["(run root)"] = groups.pop("(run root)")
    for k in sorted(groups):
        ordered[k] = groups[k]
    return ordered


def _collect_one(name_dir, run_dir, resummarize):
    """Build one run's viewer record. Returns None only if the dir holds nothing at all."""
    files, temps = _walk_files(run_dir)
    if not files:
        return None

    fileset = set(files)
    # Don't kick off a (minutes-long) summarize against a run that is still being written.
    mid_pull = bool(temps)
    summary = _ensure_summary(run_dir, resummarize, allow_summarize=not mid_pull)

    missing_core = [a for a in CORE_ARTIFACTS if a not in fileset]
    incomplete = bool(temps) or summary is None or bool(missing_core)
    reasons = []
    if temps:
        reasons.append(f"{len(temps)} rsync temp file(s) present — a pull looks in progress")
    if summary is None:
        reasons.append("summary.json missing or unreadable "
                       "(run summarize_rollouts.py where rollouts.jsonl lives)")
    if missing_core:
        reasons.append("missing " + ", ".join(missing_core))

    summary = summary or {}
    prefix = f"{name_dir.name}/{run_dir.name}"
    try:
        v = int(run_dir.stat().st_mtime)
    except OSError:
        v = 0

    figs, data, pages = [], [], []
    for rel in files:
        low = rel.lower()
        if low.endswith(".png"):
            figs.append(rel)
        elif low.endswith(".html"):
            pages.append(rel)
        elif low.endswith((".csv", ".txt", ".yaml", ".yml")) \
                and not rel.split("/")[-1].startswith("model_config_snapshot"):
            data.append(rel)

    inline = {}
    for fname, kind in [(n, "csv") for n in INLINE_CSV] + [(n, "text") for n in INLINE_TXT]:
        fp = run_dir / fname
        if not fp.exists():
            continue
        txt = _read_text(fp)
        if not txt:
            continue
        if kind == "csv":
            rows = _parse_csv(txt)
            if rows:
                inline[fname] = {"kind": "csv", "rows": rows, "href": f"{prefix}/{fname}"}
        else:
            entry = {"kind": "text", "text": txt, "href": f"{prefix}/{fname}"}
            warn = _stale_warning(fname, txt, summary)
            if warn:
                entry["warn"] = warn
            inline[fname] = entry

    try:
        forecast = _read_forecast(run_dir, prefix, summary)
    except Exception as e:                      # a malformed CSV must not sink the run
        print(f"  ! forecast CSVs unreadable for {run_dir}: {e}", file=sys.stderr)
        forecast = None

    stamp_dt = _parse_stamp(run_dir.name)
    if stamp_dt is None:
        try:
            stamp_dt = datetime.fromtimestamp(run_dir.stat().st_mtime)
        except OSError:
            stamp_dt = datetime.fromtimestamp(0)
    meta = summary.get("metadata") or {}
    groups = _group_figures(figs)

    return {
        "id": prefix,
        "name": name_dir.name,
        "stamp": run_dir.name,
        "date": stamp_dt.strftime("%Y-%m-%d %H:%M"),
        "sort_key": stamp_dt.timestamp(),
        "config": summary.get("config_name"),
        # Fall back to computing the digests here so runs summarized by an older
        # summarize_rollouts.py still show provenance (the snapshot files are pulled).
        "provenance": summary.get("provenance") or _provenance(str(run_dir), meta),
        "n_total": summary.get("n_total"),
        "sim_end": summary.get("sim_end"),
        "n_failed": summary.get("n_failed"),
        "failed_pct": summary.get("failed_pct"),
        "ac_time": summary.get("ac_time") or {},
        "ai2027_sc_time": summary.get("ai2027_sc_time") or {},
        "modes": summary.get("modes") or {},
        "metadata": meta,
        "seed": meta.get("seed"),
        "rollouts_bytes": summary.get("rollouts_bytes"),
        "has_rollouts": "rollouts.jsonl" in fileset,
        "incomplete": incomplete,
        "reasons": reasons,
        "inline": inline,
        "forecast": forecast,
        "n_figures": len(figs),
        "figure_groups": {k: [f"{prefix}/{f}?v={v}" for f in vs] for k, vs in groups.items()},
        "figure_names": groups,
        "pages": [{"rel": p, "href": f"{prefix}/{p}?v={v}"} for p in pages],
        "data_files": [{"rel": d, "href": f"{prefix}/{d}"} for d in data],
    }


def collect(root, resummarize=False):
    runs = []
    try:
        name_dirs = sorted(p for p in root.iterdir() if p.is_dir() and not p.name.startswith("."))
    except OSError:
        return runs
    for name_dir in name_dirs:
        try:
            stamps = sorted(p for p in name_dir.iterdir()
                            if p.is_dir() and not p.name.startswith("."))
        except OSError:
            continue
        for run_dir in stamps:
            try:
                rec = _collect_one(name_dir, run_dir, resummarize)
            except Exception as e:                      # never let one bad run kill the build
                print(f"  ! skipping {run_dir}: {e}", file=sys.stderr)
                continue
            if rec is not None:
                runs.append(rec)

    runs.sort(key=lambda r: r["sort_key"], reverse=True)

    # Sibling timestamps of the same run name — the MC analogue of a covert "sweep", and the
    # basis for the `latest` badge (covert marks its newest run with an outputs/latest symlink;
    # here the newest stamp per name is computed instead of symlinked).
    by_name = {}
    for r in runs:
        by_name.setdefault(r["name"], []).append(r)
    for name, group in by_name.items():
        group.sort(key=lambda r: r["sort_key"], reverse=True)
        for i, r in enumerate(group):
            r["is_latest"] = (i == 0)
            r["n_siblings"] = len(group) - 1
            r["siblings"] = [{
                "id": s["id"], "stamp": s["stamp"], "date": s["date"],
                "ac_p50": (s["ac_time"] or {}).get("p50"),
                "failed_pct": s["failed_pct"], "is_self": s["id"] == r["id"],
            } for s in group]
    return runs


