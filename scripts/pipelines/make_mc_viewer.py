PULL_HELP = """# pull a finished run (summarizes remotely, skips the ~100MB rollouts.jsonl,
# then rebuilds this viewer):
scripts/pipelines/pull_mc_run.sh /root/<remote_run>/<YYYYMMDD_HHMMSS> <local_name> [config_name]

# rebuild the viewer from whatever is already in mc_outputs/:
.venv/bin/python scripts/pipelines/make_mc_viewer.py

# serve it (relative links + file:// both work, but http avoids browser file:// quirks):
.venv/bin/python -m http.server -d mc_outputs 8010"""


def regenerate(root=DEFAULT_ROOT, resummarize=False):
    """Rebuild <root>/viewer.html. Returns (path, n_runs), or (None, 0) when there is
    nothing to show. Never raises on an empty/missing root — safe to call from a pipeline."""
    root = Path(root)
    if not root.exists():
        return None, 0
    runs = collect(root, resummarize)
    if not runs:
        return None, 0
    html = (PAGE
            .replace("/*__DATA__*/[]", json.dumps(runs, separators=(",", ":")))
            .replace('/*__PULLCMD__*/""', json.dumps(PULL_HELP))
            .replace('/*__FDIST__*/""', json.dumps(FORECAST_DIST))
            .replace('/*__FSTATS__*/""', json.dumps(FORECAST_STATS))
            .replace('/*__FCDF__*/""', json.dumps(FORECAST_CDF)))
    out = root / "viewer.html"
    # Atomic: a watcher may be regenerating the same file concurrently, and a half-written
    # viewer.html would be served to whoever has it open.
    tmp = root / f".viewer.html.{os.getpid()}.tmp"
    tmp.write_text(html)
    os.replace(tmp, out)
    return out, len(runs)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(DEFAULT_ROOT),
                    help=f"outputs root to scan (default {DEFAULT_ROOT})")
    ap.add_argument("--resummarize", action="store_true",
                    help="rebuild summary.json even when it already exists (needs rollouts.jsonl)")
    args = ap.parse_args(argv)

    root = Path(args.root)
    root.mkdir(parents=True, exist_ok=True)
    out, n = regenerate(root, args.resummarize)
    if out is None:
        sys.exit(f"no runs with a summary.json (or rollouts.jsonl) found under {root}")
    kb = out.stat().st_size / 1024
    print(f"wrote {out}  ({n} runs, {kb:.0f} KB)")
    print(f"open it with:  python -m http.server -d {root} 8010   →  http://127.0.0.1:8010/viewer.html")
    return 0


if __name__ == "__main__":
    sys.exit(main())
